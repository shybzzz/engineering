/*
  Канал стану: пристрій сам повідомляє сторінкам, що в нього змінилося
  (WebSocket, порт 81). Сторінки нічого не перепитують.

  Правило проєкту
  ---------------
  - Усе, що сторінка має показувати безперервно (стан ламп, покази датчиків,
    стан Wi-Fi, хід тривалої дії), приходить цим каналом. Сторінка не опитує
    пристрій через setInterval + fetch.
  - Дії користувача (натиснув, вибрав, ввів) — це запити до REST API
    (адреси /api/..., див. правила у скілі). Результат дії сторінка бачить
    тим самим каналом, як і всі інші відкриті сторінки.

  На пристрої
  -----------
    #include "state_socket.h"

    statePublish("lamp", "{\"on\":true}");    // тема і її стан у форматі JSON

  - Виклич statePublish() один раз у setup() (початковий стан) і далі після
    кожної зміни. Якщо стан той самий, що й минулого разу, нічого не
    надсилається — зайвий виклик не шкодить.
  - Останній стан кожної теми пам'ятається: сторінка, яка щойно відкрилась,
    одразу отримує всі теми.
  - Тем — до 8, одне повідомлення — до кількох кілобайтів. Теми "hello" і
    "alive" зайняті каналом, теми з початком "wifi" — модулем Wi-Fi.
  - Запуск і обслуговування каналу робить модуль wifi_portal (wifiPortalBegin()
    і wifiPortalLoop()); окремо викликати stateSocketBegin()/stateSocketLoop()
    треба лише в проєкті без нього.

  На сторінці
  -----------
    <script src="/state.js"></script>          перед скриптом сторінки
    <script>
      deviceState.on('lamp', data => { ... });         // щойно стан відомий і після кожної зміни
      deviceState.onLink(connected => { ... });        // зв'язок із пристроєм є / зник
    </script>

  - deviceState.connected — чи є зв'язок просто зараз.
  - Зв'язок відновлюється сам; після відновлення сторінка знову отримує всі теми.
  - Тема "hello" приходить першою після кожного підключення:
    {"via":"192.168.4.1"} — адреса пристрою, через яку відкрито сторінку.

  Як це влаштовано
  ----------------
  Повідомлення — текст {"topic":"lamp","data":{...}}. Щоп'ять секунд пристрій
  надсилає {"topic":"alive"}, сторінка відповідає; хто мовчить 15 секунд —
  того пристрій від'єднує, а сторінка, не чуючи пристрою 12 секунд,
  підключається заново. Одночасно — до 8 сторінок.
*/

#pragma once

#include <Arduino.h>
#include <WebServer.h>

// Запускає канал і додає до веб-сервера адресу /state.js (скрипт — web/state.js).
// Модуль wifi_portal викликає це сам.
void stateSocketBegin(WebServer& server);

// Викликати в кожному проході loop(). Не блокує виконання.
// Модуль wifi_portal викликає це сам.
void stateSocketLoop();

// Новий стан теми: запам'ятати і надіслати всім відкритим сторінкам.
// json — готовий JSON (об'єкт, масив, число…). Можна викликати до stateSocketBegin().
void statePublish(const char* topic, const String& json);
