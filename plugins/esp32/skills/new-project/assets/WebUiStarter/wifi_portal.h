/*
  Wi-Fi для проєктів на ESP32 з веб-інтерфейсом (Arduino, ядро esp32 3.x).

  Що робить модуль
  ----------------
  - Пристрій завжди тримає власну мережу Wi-Fi ("мережу налаштування").
    Хто підключився до неї — одразу бачить головну сторінку пристрою з
    панеллю Wi-Fi: список мереж довкола, поле пароля з кнопкою-оком,
    зрозумілі повідомлення про помилки (неправильний пароль, мережу не видно).
  - Панель Wi-Fi вбудовується у сторінки проєкту. Поки є зв'язок із домашньою
    мережею, вона згорнута в кнопку і не займає місця; натиск на кнопку
    розгортає її. Без зв'язку панель розгорнута.
  - Вибрана мережа зберігається у флеш-пам'яті (Preferences). Після ввімкнення
    пристрій підключається до неї сам; якщо її немає — пробує знову кожні
    пів хвилини. Змінити мережу можна будь-коли через мережу налаштування.
  - У домашній мережі пристрій доступний за IP-адресою та як
    http://<hostname>.local

  Світлодіод стану:  повільно блимає — немає зв'язку з домашнім Wi-Fi,
                     швидко блимає   — підключаюсь,
                     світиться       — на зв'язку.
  Кнопка скидання:   потримати 3 секунди — забути збережену мережу.

  Стан — каналом, дії — через REST API
  ------------------------------------
  Модуль запускає канал стану (state_socket.h) і сам повідомляє ним сторінкам
  про все, що стосується Wi-Fi; панель нічого не перепитує. Теми:

    "wifi"           {"state","ssid","ip","host","ap","apIp","name","error","attempt"}
                     state:   "idle" | "connecting" | "connected" | "failed";
                     error:   "" | "password" | "notfound" | "other" (коли state = "failed");
                     attempt: номер останнього підключення, замовленого зі сторінки
    "wifi-networks"  {"scan","scanning","networks":[{"ssid","rssi","open"}]}
                     scan: номер пошуку; scanning: true — пошук ще триває

  Чи відкрито сторінку через мережу налаштування, вона знає з теми "hello"
  каналу: "via" збігається з "apIp".

  Дії користувача (тіло запиту і відповідь — JSON):

    PUT  /api/wifi/network   {"ssid":"…","password":"…"} — підключитися до мережі
                             202 {"attempt":N}; що вийшло — у темі "wifi" з цим номером
    POST /api/wifi/scans     почати пошук мереж
                             202 {"scan":N}; результат — у темі "wifi-networks" з цим номером
    GET  /api/wifi           той самий стан, що в темі "wifi", — для перевірки
                             з комп'ютера (curl); сторінки цю адресу не опитують

  PUT і POST працюють лише через мережу налаштування (інакше 403); помилка
  в запиті — 400 {"error":"…"}.

  Адреси, які займає модуль
  -------------------------
    GET /wifi/panel.js   панель Wi-Fi для сторінок проєкту
    GET /wifi            окрема сторінка з тією самою панеллю (завжди розгорнутою)
    /api/wifi…           див. вище
    GET /state.js        підключення сторінки до каналу стану (state_socket.h)
    порт 81              сам канал стану (WebSocket)
  Модуль також ставить обробник "сторінку не знайдено" (див. wifiPortalHandleCaptive);
  якщо проєкт не має власної "/", там показується окрема сторінка Wi-Fi.
  Усі інші адреси, зокрема "/", належать проєкту.

  Панель Wi-Fi на сторінці проєкту
  --------------------------------
    <span id="wifi-button"></span>          де стояти кнопці (зазвичай у шапці)
    <div id="wifi-panel"></div>             де розгортатись панелі (над вмістом)
    <script src="/wifi/panel.js"></script>  наприкінці <body>

  - Без #wifi-button кнопка стане над панеллю; атрибут data-open на
    #wifi-panel лишає панель розгорнутою і при наявному зв'язку.
  - Кольори панель бере зі змінних CSS сторінки (--bg, --card, --text, --muted,
    --line, --accent, --on-accent, --danger, --danger-bg), якщо вони задані.
  - Елементи з data-wifi="name|ssid|ip|host|ap" панель заповнює сама
    (наприклад <h1 data-wifi="name">).
  - Імена, що починаються з "wp-" (id, класи), зайняті панеллю.
  - /state.js панель підключає сама, якщо сторінка цього ще не зробила.

  Використання
  ------------
    WebServer        server(80);
    WifiPortalConfig wifiConfig;

    void setup() {
      wifiConfig.deviceName = "Мій пристрій";
      wifiConfig.apSsid     = "MyDevice-Setup";
      wifiConfig.hostname   = "mydevice";
      wifiPortalBegin(server, wifiConfig);    // до server.begin()
      server.on("/", HTTP_GET, handleRoot);   // сторінки проєкту
      server.begin();
    }

    void loop() {
      wifiPortalLoop();
      server.handleClient();
    }

  Файли модуля: wifi_portal.h, wifi_portal.cpp, state_socket.h,
  state_socket.cpp (канал стану), json_tools.h (JSON), сторінки
  web/wifi.html, web/wifi-panel.js, web/state.js і пакувальник
  tools/pack-web.js.

  Сторінки (і модуля, і проєкту) лежать файлами в теці web/. Пристрій віддає
  їх стиснутими gzip: скрипт tools/pack-web.js перетворює теку web/ на
  web_pages.h, а webSend() звідти додає заголовок Content-Encoding: gzip.
  Після кожної зміни у web/ — "node tools/pack-web.js", і лише тоді збирати.
*/

#pragma once

#include <Arduino.h>
#include <WebServer.h>

struct WifiPortalConfig {
  const char* deviceName = "ESP32";          // назва пристрою на сторінках
  const char* apSsid     = "ESP32-Setup";    // назва мережі налаштування (латиницею, до 32 символів)
  const char* apPassword = "";               // "" — відкрита мережа; або пароль від 8 символів
  const char* hostname   = "esp32";          // http://<hostname>.local (малі латинські літери, цифри, дефіс)
  int8_t statusLedPin    = 2;                // світлодіод стану (GPIO2 — вбудований на більшості DevKit); -1 — немає
  int8_t resetButtonPin  = 0;                // кнопка "забути Wi-Fi" (GPIO0 — кнопка BOOT); -1 — немає
};

// Запускає мережу налаштування і канал стану, підключається до збереженої
// мережі (якщо є) і додає свої адреси до веб-сервера.
// Викликати в setup() до server.begin().
void wifiPortalBegin(WebServer& server, const WifiPortalConfig& config);

// Викликати в кожному проході loop(). Не блокує виконання.
// Обслуговує і канал стану.
void wifiPortalLoop();

// Чи є зараз зв'язок із домашньою мережею.
bool wifiPortalOnline();

// Чи прийшов запит, який зараз обробляється, через мережу налаштування
// (а не через домашню). Має сенс лише всередині обробника запиту.
bool wifiPortalFromSetupNetwork();

// Для проєктів із власним server.onNotFound(): виклич на початку свого
// обробника; якщо повернуло true — запит уже оброблено (це планшет перевіряв
// наявність інтернету, і його перенаправлено на головну сторінку пристрою).
bool wifiPortalHandleCaptive();
